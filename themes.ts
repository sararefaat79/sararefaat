// ---------------------------------------------------------------------------
// WCAG 2.1 Color Contrast Mathematics
// ---------------------------------------------------------------------------
function hexToRgb(hex: string): [number, number, number] | null {
  const clean = hex.trim().replace(/^#/, '');
  if (!/^[0-9a-fA-F]{6}$/.test(clean)) return null;
  const num = parseInt(clean, 16);
  return [(num >> 16) & 255, (num >> 8) & 255, num & 255];
}

function rgbToHex(r: number, g: number, b: number): string {
  const clamp = (n: number) => Math.max(0, Math.min(255, Math.round(n)));
  return (
    '#' +
    [clamp(r), clamp(g), clamp(b)]
      .map((v) => v.toString(16).padStart(2, '0'))
      .join('')
      .toUpperCase()
  );
}

function relativeLuminance(hex: string): number {
  const rgb = hexToRgb(hex);
  if (!rgb) return 0;
  const [r, g, b] = rgb.map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function getContrastRatio(hexA: string, hexB: string): number {
  const lumA = relativeLuminance(hexA);
  const lumB = relativeLuminance(hexB);
  const lighter = Math.max(lumA, lumB);
  const darker = Math.min(lumA, lumB);
  return (lighter + 0.05) / (darker + 0.05);
}

export function mixHex(hexA: string, hexB: string, weightB: number): string {
  const a = hexToRgb(hexA);
  const b = hexToRgb(hexB);
  if (!a || !b) return hexA;
  return rgbToHex(
    a[0] * (1 - weightB) + b[0] * weightB,
    a[1] * (1 - weightB) + b[1] * weightB,
    a[2] * (1 - weightB) + b[2] * weightB
  );
}

function pickBestReadableText(bgHex: string, lightCandidate = '#FFFFFF', darkCandidate = '#191516'): string {
  return getContrastRatio(bgHex, lightCandidate) >= getContrastRatio(bgHex, darkCandidate)
    ? lightCandidate
    : darkCandidate;
}

export function ensureContrastHex(fgHex: string, bgHex: string, minRatio = 4.5): string {
  if (getContrastRatio(fgHex, bgHex) >= minRatio) return fgHex;
  const target = relativeLuminance(bgHex) > 0.45 ? '#161213' : '#FAF7F2';
  for (let step = 1; step <= 12; step += 1) {
    const candidate = mixHex(fgHex, target, step / 12);
    if (getContrastRatio(candidate, bgHex) >= minRatio) {
      return candidate;
    }
  }
  return target;
}

export function buildCustomThemeFromColors(params: {
  id: string;
  nameAr: string;
  nameEn?: string;
  description?: string;
  primaryHex: string;
  accentHex: string;
  lightBgHex: string;
  darkBgHex: string;
}): MashaerTheme {
  const primary = /^#[0-9a-fA-F]{6}$/.test(params.primaryHex) ? params.primaryHex.toUpperCase() : '#4A0E1C';
  const accent = /^#[0-9a-fA-F]{6}$/.test(params.accentHex) ? params.accentHex.toUpperCase() : '#C5A059';
  const lightBg = /^#[0-9a-fA-F]{6}$/.test(params.lightBgHex) ? params.lightBgHex.toUpperCase() : '#FAF7F2';
  const darkBg = /^#[0-9a-fA-F]{6}$/.test(params.darkBgHex) ? params.darkBgHex.toUpperCase() : '#13080B';

  const lightSurface = '#FFFFFF';
  const lightSurfaceAlt = mixHex(lightBg, primary, 0.06);
  const lightHeading = ensureContrastHex(primary, lightSurface, 4.8);
  const lightAccentText = ensureContrastHex(accent, lightSurface, 4.5);
  const lightSidebar = ensureContrastHex(primary, '#FFFFFF', 4.6);
  const lightSidebarAlt = mixHex(lightSidebar, '#000000', 0.28);
  const lightSidebarText = pickBestReadableText(lightSidebar, '#FFFFFF', '#191516');
  const lightButton = lightSidebar;
  const lightButtonText = pickBestReadableText(lightButton, '#FFFFFF', '#191516');

  const darkSurface = mixHex(darkBg, '#FFFFFF', 0.05);
  const darkSurfaceAlt = mixHex(darkBg, '#FFFFFF', 0.09);
  const darkAccentSoft = ensureContrastHex(mixHex(accent, '#FFFFFF', 0.25), darkSurface, 4.6);
  const darkButton = darkAccentSoft;
  const darkButtonText = pickBestReadableText(darkButton, '#FFFFFF', '#161213');
  const darkSidebar = mixHex(darkBg, primary, 0.22);
  const darkSidebarAlt = mixHex(darkSidebar, '#000000', 0.35);

  return {
    id: params.id,
    nameAr: params.nameAr.trim() || 'ثيم مخصص',
    nameEn: (params.nameEn || 'Custom Brand Theme').trim(),
    perfumeSource: 'تصميم مخصص',
    description: (params.description || 'ثيم ألوان مخصص معتمد ومتحقق التباين لوضوح القراءة.').trim(),
    swatchHexes: [primary, accent, lightBg, darkBg, darkAccentSoft],
    isCustom: true,
    light: {
      primary: lightHeading,
      heading: lightHeading,
      secondary: mixHex(primary, '#FFFFFF', 0.16),
      accent: lightAccentText,
      accentSoft: accent,
      bg: lightBg,
      surface: lightSurface,
      surfaceAlt: lightSurfaceAlt,
      text: ensureContrastHex('#1E1618', lightBg, 7),
      muted: ensureContrastHex('#5D4C51', lightSurface, 4.6),
      border: mixHex(lightBg, primary, 0.14),
      sidebar: lightSidebar,
      sidebarAlt: lightSidebarAlt,
      sidebarText: lightSidebarText,
      sidebarAccent: ensureContrastHex(mixHex(accent, '#FFFFFF', 0.35), lightSidebar, 4.5),
      button: lightButton,
      buttonHover: mixHex(lightButton, '#FFFFFF', 0.12),
      buttonText: lightButtonText,
    },
    dark: {
      primary: darkAccentSoft,
      heading: '#F5EFE6',
      secondary: primary,
      accent: darkAccentSoft,
      accentSoft: accent,
      bg: darkBg,
      surface: darkSurface,
      surfaceAlt: darkSurfaceAlt,
      text: '#F5EFE6',
      muted: ensureContrastHex('#C8B8BD', darkSurface, 4.6),
      border: mixHex(darkSurface, '#FFFFFF', 0.16),
      sidebar: darkSidebar,
      sidebarAlt: darkSidebarAlt,
      sidebarText: '#F5EFE6',
      sidebarAccent: darkAccentSoft,
      button: darkButton,
      buttonHover: mixHex(darkButton, '#FFFFFF', 0.15),
      buttonText: darkButtonText,
    },
  };
}

export function findThemeById(themeId: string | undefined, customThemes?: MashaerTheme[]): MashaerTheme {
  const all = [...BUILT_IN_THEMES, ...(customThemes || [])];
  return all.find((t) => t.id === themeId) || BUILT_IN_THEMES[0];
}

export function resolveThemeTokens(
  themeId: string | undefined,
  mode: 'light' | 'dark',
  customThemes?: MashaerTheme[]
): { theme: MashaerTheme; tokens: ThemeColorSet } {
  const theme = findThemeById(themeId, customThemes);
  return {
    theme,
    tokens: mode === 'dark' ? theme.dark : theme.light,
  };
}

export function applyThemeToDocument(
  themeId: string | undefined,
  mode: 'light' | 'dark',
  customThemes?: MashaerTheme[]
): { theme: MashaerTheme; tokens: ThemeColorSet } {
  const { theme, tokens } = resolveThemeTokens(themeId, mode, customThemes);
  const root = document.documentElement;
  root.style.setProperty('--hub-primary', tokens.primary);
  root.style.setProperty('--hub-heading', tokens.heading);
  root.style.setProperty('--hub-secondary', tokens.secondary);
  root.style.setProperty('--hub-accent', tokens.accent);
  root.style.setProperty('--hub-accent-soft', tokens.accentSoft);
  root.style.setProperty('--hub-bg', tokens.bg);
  root.style.setProperty('--hub-surface', tokens.surface);
  root.style.setProperty('--hub-surface-alt', tokens.surfaceAlt);
  root.style.setProperty('--hub-text', tokens.text);
  root.style.setProperty('--hub-muted', tokens.muted);
  root.style.setProperty('--hub-border', tokens.border);
  root.style.setProperty('--hub-sidebar', tokens.sidebar);
  root.style.setProperty('--hub-sidebar-alt', tokens.sidebarAlt);
  root.style.setProperty('--hub-sidebar-text', tokens.sidebarText);
  root.style.setProperty('--hub-sidebar-accent', tokens.sidebarAccent);
  root.style.setProperty('--hub-button', tokens.button);
  root.style.setProperty('--hub-button-hover', tokens.buttonHover);
  root.style.setProperty('--hub-button-text', tokens.buttonText);
  return { theme, tokens };
}
